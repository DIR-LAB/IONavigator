def rotate_diagnoses(rotate_by):
    diagnosis_list = ["Tool-1 Diagnosis: {ION2_diagnosis}", "Tool-2 Diagnosis: {Drishti_diagnosis}", "Tool-3 Diagnosis: {ION1_diagnosis}", "Tool-4 Diagnosis: {ION2_Llama_diagnosis}"]
    rotate_by = rotate_by % len(diagnosis_list)
    diagnosis_list = diagnosis_list[rotate_by:] + diagnosis_list[:rotate_by]
    return "\n\n".join(diagnosis_list)

def rotate_ranks(rotate_by):
    order_of_ranks = ["Tool-1: <Rank of Tool-1 diagnosis>", "Tool-2: <Rank of Tool-2 diagnosis>", "Tool-3: <Rank of Tool-3 diagnosis>", "Tool-4: <Rank of Tool-4 diagnosis>"]
    rotate_by = rotate_by % len(order_of_ranks)
    order_of_ranks = order_of_ranks[rotate_by:] + order_of_ranks[:rotate_by]
    return "\n".join(order_of_ranks)


def format_messages(prompt_type, kwargs):
    if "rank_criteria" in kwargs:
        if kwargs["rank_criteria"] == "Accuracy":
            kwargs["rank_criteria"] = rank_criterium[kwargs["rank_criteria"]].format(labels="\n".join([f"{label_name}: {label_description}" for label_name, label_description in kwargs["labels"].items()]))
        else:
            kwargs["rank_criteria"] = rank_criterium[kwargs["rank_criteria"]]
    prompt_template = prompt_templates[prompt_type]
    messages = []
    
    if prompt_type == "compare_diagnoses":
        order_of_ranks = rotate_ranks(kwargs["rotate_by"])
        messages.append({"role": "system", "content": prompt_template["system_context"]["prompt"].format(order_of_ranks=order_of_ranks, **kwargs)})
        messages.append({"role": "user", "content": rotate_diagnoses(kwargs["rotate_by"]).format(**kwargs)})
    else:
        messages.append({"role": "system", "content": prompt_template["system_context"]["prompt"].format(**kwargs)})
        messages.append({"role": "user", "content": prompt_template["user_prompt"]["prompt"].format(**kwargs)})
    return messages

